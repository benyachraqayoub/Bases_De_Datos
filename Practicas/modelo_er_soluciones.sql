CREATE SCHEMA IF NOT EXISTS ejercicio7_red_profesional;
SET search_path TO ejercicio7_red_profesional;

CREATE TABLE usuario (
    identificador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    fecha_alta DATE NOT NULL,
    es_fundador BOOLEAN NOT NULL DEFAULT FALSE,
    invitado_por BIGINT REFERENCES usuario(identificador),
    CHECK (
        (es_fundador AND invitado_por IS NULL)
        OR
        (NOT es_fundador AND invitado_por IS NOT NULL)
    ),
    CHECK (invitado_por IS NULL OR invitado_por <> identificador)
);

CREATE TABLE seguimiento (
    seguidor BIGINT NOT NULL REFERENCES usuario(identificador),
    seguido BIGINT NOT NULL REFERENCES usuario(identificador),
    fecha_inicio DATE NOT NULL,
    PRIMARY KEY (seguidor, seguido),
    CHECK (seguidor <> seguido)
);

CREATE TABLE bloqueo (
    bloqueador BIGINT NOT NULL REFERENCES usuario(identificador),
    bloqueado BIGINT NOT NULL REFERENCES usuario(identificador),
    motivo TEXT NOT NULL,
    PRIMARY KEY (bloqueador, bloqueado),
    CHECK (bloqueador <> bloqueado)
);

CREATE SCHEMA IF NOT EXISTS ejercicio8_complejo_hospitalario;
SET search_path TO ejercicio8_complejo_hospitalario;

CREATE TABLE edificio (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    direccion VARCHAR(200) NOT NULL
);

CREATE TABLE planta (
    codigo_edificio BIGINT NOT NULL REFERENCES edificio(codigo),
    numero_planta INTEGER NOT NULL CHECK (numero_planta >= 0),
    uso VARCHAR(100) NOT NULL,
    PRIMARY KEY (codigo_edificio, numero_planta)
);

CREATE TABLE habitacion (
    codigo_edificio BIGINT NOT NULL,
    numero_planta INTEGER NOT NULL,
    numero_habitacion INTEGER NOT NULL CHECK (numero_habitacion >= 0),
    numero_camas SMALLINT NOT NULL CHECK (numero_camas > 0),
    PRIMARY KEY (codigo_edificio, numero_planta, numero_habitacion),
    FOREIGN KEY (codigo_edificio, numero_planta)
        REFERENCES planta(codigo_edificio, numero_planta)
);

CREATE TABLE paciente (
    numero_historia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE ingreso (
    numero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_historia BIGINT NOT NULL REFERENCES paciente(numero_historia),
    codigo_edificio BIGINT NOT NULL,
    numero_planta INTEGER NOT NULL,
    numero_habitacion INTEGER NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_alta DATE,
    FOREIGN KEY (codigo_edificio, numero_planta, numero_habitacion)
        REFERENCES habitacion(
            codigo_edificio,
            numero_planta,
            numero_habitacion
        ),
    CHECK (fecha_alta IS NULL OR fecha_alta >= fecha_ingreso)
);
