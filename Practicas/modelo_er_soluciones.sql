-- Soluciones de los ocho ejercicios del modelo E/R.
-- Dialecto: PostgreSQL. Cada ejercicio se crea en su propio esquema.

CREATE SCHEMA IF NOT EXISTS ejercicio1_taller;
SET search_path TO ejercicio1_taller;

CREATE TABLE cliente (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL
);

CREATE TABLE vehiculo (
    matricula VARCHAR(10) PRIMARY KEY,
    marca VARCHAR(50) NOT NULL,
    modelo VARCHAR(50) NOT NULL,
    dni_cliente VARCHAR(9) NOT NULL REFERENCES cliente(dni)
);

CREATE TABLE reparacion (
    numero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(10) NOT NULL REFERENCES vehiculo(matricula),
    fecha_entrada DATE NOT NULL,
    descripcion_averia TEXT NOT NULL,
    importe NUMERIC(10, 2) NOT NULL CHECK (importe >= 0)
);

CREATE SCHEMA IF NOT EXISTS ejercicio2_academia;
SET search_path TO ejercicio2_academia;

CREATE TABLE alumno (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL
);

CREATE TABLE profesor (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    especialidad VARCHAR(100) NOT NULL
);

CREATE TABLE curso (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idioma VARCHAR(60) NOT NULL,
    nivel VARCHAR(30) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL CHECK (precio >= 0),
    dni_profesor VARCHAR(9) NOT NULL REFERENCES profesor(dni)
);

CREATE TABLE matricula (
    codigo_alumno BIGINT NOT NULL REFERENCES alumno(codigo),
    codigo_curso BIGINT NOT NULL REFERENCES curso(codigo),
    fecha DATE NOT NULL,
    nota_final NUMERIC(4, 2) CHECK (nota_final BETWEEN 0 AND 10),
    PRIMARY KEY (codigo_alumno, codigo_curso)
);

CREATE SCHEMA IF NOT EXISTS ejercicio3_liga;
SET search_path TO ejercicio3_liga;

CREATE TABLE equipo (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    ciudad VARCHAR(100) NOT NULL
);

CREATE TABLE jugador (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    dorsal SMALLINT NOT NULL CHECK (dorsal > 0),
    posicion VARCHAR(50) NOT NULL,
    codigo_equipo BIGINT NOT NULL REFERENCES equipo(codigo)
);

CREATE TABLE partido (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    goles_local SMALLINT NOT NULL CHECK (goles_local >= 0),
    goles_visitante SMALLINT NOT NULL CHECK (goles_visitante >= 0),
    equipo_local BIGINT NOT NULL REFERENCES equipo(codigo),
    equipo_visitante BIGINT NOT NULL REFERENCES equipo(codigo),
    CHECK (equipo_local <> equipo_visitante)
);

CREATE SCHEMA IF NOT EXISTS ejercicio4_empresa;
SET search_path TO ejercicio4_empresa;

CREATE TABLE departamento (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE empleado (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    salario NUMERIC(12, 2) NOT NULL CHECK (salario >= 0),
    codigo_departamento BIGINT NOT NULL REFERENCES departamento(codigo),
    dni_jefe VARCHAR(9) REFERENCES empleado(dni),
    CHECK (dni_jefe IS NULL OR dni_jefe <> dni)
);

CREATE TABLE proyecto (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    presupuesto NUMERIC(14, 2) NOT NULL CHECK (presupuesto >= 0)
);

CREATE TABLE participacion (
    dni_empleado VARCHAR(9) NOT NULL REFERENCES empleado(dni),
    codigo_proyecto BIGINT NOT NULL REFERENCES proyecto(codigo),
    horas NUMERIC(8, 2) NOT NULL CHECK (horas > 0),
    PRIMARY KEY (dni_empleado, codigo_proyecto)
);

CREATE SCHEMA IF NOT EXISTS ejercicio5_hospital;
SET search_path TO ejercicio5_hospital;

CREATE TABLE planta (
    numero INTEGER PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE personal (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('MEDICO', 'ENFERMERO')),
    numero_colegiado VARCHAR(30) UNIQUE,
    especialidad VARCHAR(100),
    turno VARCHAR(30),
    numero_planta INTEGER REFERENCES planta(numero),
    UNIQUE (dni, tipo),
    CHECK (
        (
            tipo = 'MEDICO'
            AND numero_colegiado IS NOT NULL
            AND especialidad IS NOT NULL
            AND turno IS NULL
            AND numero_planta IS NULL
        )
        OR
        (
            tipo = 'ENFERMERO'
            AND numero_colegiado IS NULL
            AND especialidad IS NULL
            AND turno IS NOT NULL
            AND numero_planta IS NOT NULL
        )
    )
);

CREATE TABLE paciente (
    numero_historia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL
);

CREATE TABLE consulta (
    numero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_historia BIGINT NOT NULL REFERENCES paciente(numero_historia),
    dni_medico VARCHAR(9) NOT NULL,
    tipo_personal VARCHAR(12) NOT NULL DEFAULT 'MEDICO'
        CHECK (tipo_personal = 'MEDICO'),
    fecha TIMESTAMP NOT NULL,
    diagnostico TEXT NOT NULL,
    FOREIGN KEY (dni_medico, tipo_personal) REFERENCES personal(dni, tipo)
);

