-- Soluciones de los ocho ejercicios del modelo E/R.
-- Dialecto: PostgreSQL. Cada ejercicio se crea en su propio esquema.

CREATE SCHEMA IF NOT EXISTS ejercicio1_taller;
SET search_path TO ejercicio1_taller;

CREATE TABLE cliente (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL
);

CREATE TABLE vehiculo (
    matricula VARCHAR(10) PRIMARY KEY,
    marca VARCHAR(50) NOT NULL,
    modelo VARCHAR(50) NOT NULL,
    dni_cliente VARCHAR(9) NOT NULL,
    CONSTRAINT fk_vehiculo_cliente FOREIGN KEY (dni_cliente) REFERENCES cliente(dni)
);

CREATE TABLE reparacion (
    numero INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(10) NOT NULL,
    fecha_entrada DATE NOT NULL,
    descripcion_averia TEXT NOT NULL,
    importe NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_reparacion_vehiculo FOREIGN KEY (matricula) REFERENCES vehiculo(matricula)
);

CREATE SCHEMA IF NOT EXISTS ejercicio2_academia;
SET search_path TO ejercicio2_academia;

CREATE TABLE alumno (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL
);

CREATE TABLE profesor (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    especialidad VARCHAR(100) NOT NULL
);

CREATE TABLE curso (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idioma VARCHAR(60) NOT NULL,
    nivel VARCHAR(30) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL,
    dni_profesor VARCHAR(9) NOT NULL,
    CONSTRAINT fk_curso_profesor FOREIGN KEY (dni_profesor) REFERENCES profesor(dni)
);

CREATE TABLE matricula (
    codigo_alumno INT NOT NULL,
    codigo_curso INT NOT NULL,
    fecha DATE NOT NULL,
    nota_final NUMERIC(4, 2),
    PRIMARY KEY (codigo_alumno, codigo_curso),
    CONSTRAINT fk_matricula_alumno FOREIGN KEY (codigo_alumno) REFERENCES alumno(codigo),
    CONSTRAINT fk_matricula_curso FOREIGN KEY (codigo_curso) REFERENCES curso(codigo)
);

CREATE SCHEMA IF NOT EXISTS ejercicio3_liga;
SET search_path TO ejercicio3_liga;

CREATE TABLE equipo (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    ciudad VARCHAR(100) NOT NULL
);

CREATE TABLE jugador (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    dorsal INT NOT NULL,
    posicion VARCHAR(50) NOT NULL,
    codigo_equipo INT NOT NULL,
    CONSTRAINT fk_jugador_equipo FOREIGN KEY (codigo_equipo) REFERENCES equipo(codigo)
);

CREATE TABLE partido (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    goles_local INT NOT NULL,
    goles_visitante INT NOT NULL,
    equipo_local INT NOT NULL,
    equipo_visitante INT NOT NULL,
    CONSTRAINT fk_partido_equipo_local FOREIGN KEY (equipo_local) REFERENCES equipo(codigo),
    CONSTRAINT fk_partido_equipo_visitante FOREIGN KEY (equipo_visitante) REFERENCES equipo(codigo)
);

CREATE SCHEMA IF NOT EXISTS ejercicio4_empresa;
SET search_path TO ejercicio4_empresa;

CREATE TABLE departamento (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE empleado (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    salario NUMERIC(12, 2) NOT NULL,
    codigo_departamento INT NOT NULL,
    dni_jefe VARCHAR(9),
    CONSTRAINT fk_empleado_departamento FOREIGN KEY (codigo_departamento) REFERENCES departamento(codigo),
    CONSTRAINT fk_empleado_jefe FOREIGN KEY (dni_jefe) REFERENCES empleado(dni)
);

CREATE TABLE proyecto (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    presupuesto NUMERIC(14, 2) NOT NULL
);

CREATE TABLE participacion (
    dni_empleado VARCHAR(9) NOT NULL,
    codigo_proyecto INT NOT NULL,
    horas NUMERIC(8, 2) NOT NULL,
    PRIMARY KEY (dni_empleado, codigo_proyecto),
    CONSTRAINT fk_participacion_empleado FOREIGN KEY (dni_empleado) REFERENCES empleado(dni),
    CONSTRAINT fk_participacion_proyecto FOREIGN KEY (codigo_proyecto) REFERENCES proyecto(codigo)
);

CREATE SCHEMA IF NOT EXISTS ejercicio5_hospital;
SET search_path TO ejercicio5_hospital;

CREATE TABLE planta (
    numero INT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE personal (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    tipo VARCHAR(12) NOT NULL,
    numero_colegiado VARCHAR(30) UNIQUE,
    especialidad VARCHAR(100),
    turno VARCHAR(30),
    numero_planta INT,
    UNIQUE (dni, tipo),
    CONSTRAINT fk_personal_planta FOREIGN KEY (numero_planta) REFERENCES planta(numero)
);

CREATE TABLE paciente (
    numero_historia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL
);

CREATE TABLE consulta (
    numero INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_historia INT NOT NULL,
    dni_medico VARCHAR(9) NOT NULL,
    tipo_personal VARCHAR(12) NOT NULL DEFAULT 'MEDICO',
    fecha TIMESTAMP NOT NULL,
    diagnostico TEXT NOT NULL,
    CONSTRAINT fk_consulta_paciente FOREIGN KEY (numero_historia) REFERENCES paciente(numero_historia),
    CONSTRAINT fk_consulta_personal FOREIGN KEY (dni_medico, tipo_personal) REFERENCES personal(dni, tipo)
);

CREATE SCHEMA IF NOT EXISTS ejercicio6_docencia;
SET search_path TO ejercicio6_docencia;

CREATE TABLE profesor (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE asignatura (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    horas_semanales NUMERIC(4, 1) NOT NULL
);

CREATE TABLE grupo_clase (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso VARCHAR(30) NOT NULL,
    turno VARCHAR(30) NOT NULL
);

CREATE TABLE docencia (
    codigo_asignatura INT NOT NULL,
    codigo_grupo INT NOT NULL,
    dni_profesor VARCHAR(9) NOT NULL,
    aula VARCHAR(30) NOT NULL,
    PRIMARY KEY (codigo_asignatura, codigo_grupo),
    CONSTRAINT fk_docencia_asignatura FOREIGN KEY (codigo_asignatura) REFERENCES asignatura(codigo),
    CONSTRAINT fk_docencia_grupo FOREIGN KEY (codigo_grupo) REFERENCES grupo_clase(codigo),
    CONSTRAINT fk_docencia_profesor FOREIGN KEY (dni_profesor) REFERENCES profesor(dni)
);

CREATE SCHEMA IF NOT EXISTS ejercicio7_red_profesional;
SET search_path TO ejercicio7_red_profesional;

CREATE TABLE usuario (
    identificador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    fecha_alta DATE NOT NULL,
    es_fundador BOOLEAN NOT NULL DEFAULT FALSE,
    invitado_por INT,
    CONSTRAINT fk_usuario_invitador FOREIGN KEY (invitado_por) REFERENCES usuario(identificador)
);

CREATE TABLE seguimiento (
    seguidor INT NOT NULL,
    seguido INT NOT NULL,
    fecha_inicio DATE NOT NULL,
    PRIMARY KEY (seguidor, seguido),
    CONSTRAINT fk_seguimiento_seguidor FOREIGN KEY (seguidor) REFERENCES usuario(identificador),
    CONSTRAINT fk_seguimiento_seguido FOREIGN KEY (seguido) REFERENCES usuario(identificador)
);

CREATE TABLE bloqueo (
    bloqueador INT NOT NULL,
    bloqueado INT NOT NULL,
    motivo TEXT NOT NULL,
    PRIMARY KEY (bloqueador, bloqueado),
    CONSTRAINT fk_bloqueo_bloqueador FOREIGN KEY (bloqueador) REFERENCES usuario(identificador),
    CONSTRAINT fk_bloqueo_bloqueado FOREIGN KEY (bloqueado) REFERENCES usuario(identificador)
);

CREATE SCHEMA IF NOT EXISTS ejercicio8_complejo_hospitalario;
SET search_path TO ejercicio8_complejo_hospitalario;

CREATE TABLE edificio (
    codigo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    direccion VARCHAR(200) NOT NULL
);

CREATE TABLE planta (
    codigo_edificio INT NOT NULL,
    numero_planta INT NOT NULL,
    uso VARCHAR(100) NOT NULL,
    PRIMARY KEY (codigo_edificio, numero_planta),
    CONSTRAINT fk_planta_edificio FOREIGN KEY (codigo_edificio) REFERENCES edificio(codigo)
);

CREATE TABLE habitacion (
    codigo_edificio INT NOT NULL,
    numero_planta INT NOT NULL,
    numero_habitacion INT NOT NULL,
    numero_camas INT NOT NULL,
    PRIMARY KEY (codigo_edificio, numero_planta, numero_habitacion),
    CONSTRAINT fk_habitacion_planta FOREIGN KEY (codigo_edificio, numero_planta)
        REFERENCES planta(codigo_edificio, numero_planta)
);

CREATE TABLE paciente (
    numero_historia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE ingreso (
    numero INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_historia INT NOT NULL,
    codigo_edificio INT NOT NULL,
    numero_planta INT NOT NULL,
    numero_habitacion INT NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_alta DATE,
    CONSTRAINT fk_ingreso_paciente FOREIGN KEY (numero_historia) REFERENCES paciente(numero_historia),
    CONSTRAINT fk_ingreso_habitacion FOREIGN KEY (codigo_edificio, numero_planta, numero_habitacion)
        REFERENCES habitacion(
            codigo_edificio,
            numero_planta,
            numero_habitacion
        )
);
